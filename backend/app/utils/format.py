def render_markdown_report(report: dict) -> str:
    scenarios = "\n".join(
        f"| **{s.get('label', s.get('type'))}** | {s.get('price_target', '')} | {s.get('probability', '')} | {s.get('thesis', '')} |"
        for s in report.get("scenarios") or []
    )
    sizing = report.get("position_sizing") or {}
    strategy = "\n".join(
        f"{i}. {s}" for i, s in enumerate(report.get("investment_strategy") or [], 1)
    )
    catalysts = "\n".join(
        f"- **[{str(c.get('type', '')).upper()}]** {c.get('label')} *({c.get('timeline')})*: {c.get('detail')}"
        for c in report.get("catalysts") or []
    )
    risks = "\n".join(
        f"- **{r.get('name')}** — Risk score: {r.get('score')}/10. {r.get('description')}"
        for r in report.get("risks") or []
    )
    health = "\n".join(
        f"- **{f.get('metric')}**: {f.get('value')} ({f.get('assessment')}) — {f.get('note')}"
        for f in report.get("financial_health") or []
    )
    pred = "\n".join(
        f"- **{p.get('dimension')}**: {p.get('score')}/10 — {p.get('rationale')}"
        for p in report.get("predictability_scores") or []
    )
    invalid = "\n".join(
        f"{i}. {t}" for i, t in enumerate(report.get("thesis_invalidators") or [], 1)
    )
    return f"""# {report.get('ticker')} — {report.get('verdict')}
**{report.get('title')}**
*Generated: {report.get('generated_at')} | Provider: {report.get('provider_used')}*

---

## Executive Summary
{report.get('summary')}

| Field | Value |
|---|---|
| Conviction | {report.get('conviction')}/10 |
| Price target (base) | {report.get('price_target_base')} ({report.get('implied_upside_base')}) |
| Bull / Bear targets | {report.get('price_target_bull')} / {report.get('price_target_bear')} |
| Risk level | {report.get('risk_level')} |
| Time horizon | {report.get('horizon')} — {report.get('horizon_note')} |
| Agent consensus | {report.get('consensus_score')}/10 — {report.get('consensus_description')} |

---

## Scenario Analysis

| Scenario | Target | Probability | Thesis |
|---|---|---|---|
{scenarios}

---

## Investment Strategy

{strategy}

**Position sizing:**
- Aggressive: {sizing.get('aggressive_investor')}
- Moderate: {sizing.get('moderate_investor')}
- Conservative: {sizing.get('conservative_investor')}

---

## Key Catalysts

{catalysts}

---

## Risk Assessment

{risks}

---

## Financial Health

{health}

---

## Predictability Scores

{pred}

---

## Thesis Invalidators

{invalid}

---

## Disclaimer

*This analysis is generated by AI language models and is for informational and educational purposes only. It does not constitute financial advice, a solicitation to buy or sell any security, or a guarantee of future performance. Always conduct your own due diligence and consult a qualified financial advisor before making investment decisions.*
"""
